/**
 * @fileoverview Benchmark configuration: StarBench (the BKR reification benchmark) and the workloads added
 * next to it, LUBM and OAEI Conference.
 *
 * For StarBench this wires together, for each RDF reification pattern:
 *  - the CONSTRUCT mappers that expose the RDF 1.1 data as an RDF 1.2 view, and
 *  - the materialized RDF 1.1 dataset produced by `data/run-conversion.sh`.
 * For the other workloads, see {@link WorkloadConfig}.
 *
 * The SPARQL 1.2 user queries come from `queries/BKR-star_*.rq` and are fed to the
 * rewriter verbatim: the parser desugars their `<< s p o >>` reifier syntax into the
 * `rdf:reifies <<( s p o )>>` triple-term form itself, so no pre-conversion is needed.
 */
import { existsSync, readdirSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  bkrNonReificationConstruct,
  bkrNonSingletonConstruct,
  bkrReificationConstruct,
  singletonPropertyConstruct,
} from '../queryConsts.js';
import type { EngineSource } from './engines.js';
import type { BenchCase } from './runner.js';

const HERE = dirname(fileURLToPath(import.meta.url));
const BKR_ROOT = join(HERE, '..', 'statics', 'REF-Benchmark', 'BKR');
const QUERY_DIR = join(BKR_ROOT, 'queries');
const DATA_DIR = join(BKR_ROOT, 'data');

/** A reification pattern: how RDF 1.2 statements are materialized in RDF 1.1. */
export interface PatternConfig {
  /** Pattern id used in case ids and reporting. */
  name: string;
  /** CONSTRUCT mappers (RDF 1.1 -> RDF 1.2 view) for this pattern. */
  mappers: string[];
  /** Materialized RDF 1.1 dataset filename under `data/`. */
  dataFile: string;
  /**
   * Filename prefix of the hand-written "baseline" queries written directly
   * against this pattern's RDF 1.1 materialization (e.g. `BKR-R` for classic
   * reification, `BKR-S` for singleton properties). These are the "original
   * query on the original data" the rewriting approach is compared against.
   */
  baselinePrefix: string;
}

/**
 * The reification patterns the benchmark can exercise. Each corresponds to one of
 * the datasets generated by `data/mapBkrStar.ts` / `run-conversion.sh`.
 */
export const PATTERNS: Record<string, PatternConfig> = {
  reification: {
    name: 'reification',
    mappers: [ bkrReificationConstruct, bkrNonReificationConstruct ],
    dataFile: 'BKR-Reification.ttl',
    baselinePrefix: 'BKR-R',
  },
  singleton: {
    name: 'singleton',
    mappers: [ singletonPropertyConstruct, bkrNonSingletonConstruct ],
    dataFile: 'BKR-Singleton.ttl',
    baselinePrefix: 'BKR-S',
  },
};

/** Reads a query file verbatim. */
export function loadRawQuery(fileName: string): string {
  return readFileSync(join(QUERY_DIR, fileName), 'utf8');
}

/**
 * Lists the BKR-star query file names (e.g. `BKR-star_A-Q1.rq`) that only contain
 * SELECT queries the rewriter can currently handle. Optionally filtered by a
 * predicate on the raw query text.
 */
export function listStarQueryFiles(filter?: (raw: string) => boolean): string[] {
  return readdirSync(QUERY_DIR)
    .filter(name => /^BKR-star_.*\.rq$/u.test(name))
    .filter((name) => {
      const raw = readFileSync(join(QUERY_DIR, name), 'utf8');
      return /select/iu.test(raw) && (filter ? filter(raw) : true);
    })
    .sort();
}

/**
 * Builds benchmark cases for the given pattern by pairing every BKR-star SELECT
 * query with that pattern's mappers, its materialized dataset, and the parallel
 * hand-written baseline query.
 *
 * The SPARQL 1.2 `<< s p o >>` reifier syntax is fed to the rewriter verbatim:
 * the parser desugars it into the `rdf:reifies <<( s p o )>>` triple-term form, so
 * no textual pre-conversion is needed.
 *
 * @param patternName - Key into {@link PATTERNS}.
 * @param materializedFile - Optional path to the RDF 1.1 dataset (or a subset) to
 *   run against. Defaults to the full dataset under `data/`.
 * @param queryFilter - Optional predicate to restrict which query files are used.
 */
export function buildCases(
  patternName: keyof typeof PATTERNS,
  materializedFile?: string,
  queryFilter?: (raw: string) => boolean,
): BenchCase[] {
  const pattern = PATTERNS[patternName];
  const file = materializedFile ?? join(DATA_DIR, pattern.dataFile);
  return listStarQueryFiles(queryFilter).map((fileName) => {
    const stem = fileName.replace(/^BKR-star_/u, '').replace(/\.rq$/u, '');
    const id = `${pattern.name}/${stem}`;
    const baselineFile = `${pattern.baselinePrefix}_${stem}.rq`;
    return {
      id,
      pattern: pattern.name,
      mappers: pattern.mappers,
      userQuery12: loadRawQuery(fileName),
      baselineQuery: existsSync(join(QUERY_DIR, baselineFile)) ?
        loadRawQuery(baselineFile) :
        undefined,
      materialized: { name: pattern.dataFile, file },
    };
  });
}

/** How views files separate one CONSTRUCT from the next (see `workloads/*\/views.rq`). */
const VIEW_SEPARATOR = /\n# ----\n/u;

/** Reads a workload's views file into one CONSTRUCT string per view. */
export function loadViews(file: string): string[] {
  return readFileSync(file, 'utf8').split(VIEW_SEPARATOR).map(view => view.trim()).filter(Boolean);
}

const WORKLOADS_DIR = join(HERE, 'workloads');

/**
 * A workload with no hand-written query over its source data: LUBM and OAEI Conference. Its reference is
 * the original query run over the **materialised views** (`materializeViews.ts`), and that is what its
 * `materialized` approach measures - the query against a graph with every view already computed.
 */
export interface WorkloadConfig {
  name: string;
  /** Views, as written by the workload's generator script. */
  viewsFile: string;
  /** One SELECT per `.rq` file. */
  queryDir: string;
  /**
   * Scale name -> file stem under the workload's `data/` directory, in the order to run them. Each stem
   * has `<stem>.nt` (skolemised source), `<stem>.views.nt` (materialised views) and, where Comunica runs,
   * `.hdt` copies of both.
   */
  scales: Record<string, string>;
  /**
   * Scales that only some engines run, by scale name; every other scale runs on every engine. A scale can be
   * sized for the engines that take it: LUBM's `u250` is about where QLever needs five minutes to
   * materialise the views, a point the other engines reach at `u100` or well below.
   */
  scaleEngines?: Record<string, string[]>;
  /**
   * Whether every scale's data contains the previous one's, so that a query timing out at one scale
   * would time out at the next as well and need not be run there. True for LUBM, whose generator makes
   * the same University0 whatever the number of universities.
   */
  nestedScales: boolean;
}

export const WORKLOADS: Record<string, WorkloadConfig> = {
  lubm: {
    name: 'lubm',
    viewsFile: join(WORKLOADS_DIR, 'lubm', 'views.rq'),
    queryDir: join(WORKLOADS_DIR, 'lubm', 'queries'),
    scales: { u1: 'lubm-u1', u10: 'lubm-u10', u50: 'lubm-u50', u100: 'lubm-u100', u250: 'lubm-u250' },
    scaleEngines: { u250: [ 'qlever' ]},
    nestedScales: true,
  },
  oaei: {
    name: 'oaei',
    viewsFile: join(WORKLOADS_DIR, 'oaei', 'views.rq'),
    queryDir: join(WORKLOADS_DIR, 'oaei', 'queries'),
    scales: { d100: 'oaei-100', eswc: 'oaei-eswc' },
    nestedScales: false,
  },
};

/** Whether `engine` runs `workload` at `scale` (see {@link WorkloadConfig.scaleEngines}). */
export function runsAt(workload: WorkloadConfig, scale: string, engine: string): boolean {
  return workload.scaleEngines?.[scale]?.includes(engine) ?? true;
}

/** The source and materialised-views datasets of one workload scale. */
export function workloadSources(workload: WorkloadConfig, scale: string): {
  source: EngineSource;
  views: EngineSource;
} {
  const stem = join(WORKLOADS_DIR, workload.name, 'data', workload.scales[scale]);
  return {
    source: { name: `${workload.name}-${scale}`, file: `${stem}.nt`, hdtFile: `${stem}.hdt` },
    views: { name: `${workload.name}-${scale}-views`, file: `${stem}.views.nt`, hdtFile: `${stem}.views.hdt` },
  };
}

/**
 * Builds a workload's cases. The user query doubles as the `baselineQuery`: run over the materialised
 * views rather than the source, it is the reference every rewriting is graded against.
 */
export function buildWorkloadCases(workload: WorkloadConfig): BenchCase[] {
  const mappers = loadViews(workload.viewsFile);
  return readdirSync(workload.queryDir)
    .filter(name => name.endsWith('.rq'))
    .sort()
    .map((fileName) => {
      const query = readFileSync(join(workload.queryDir, fileName), 'utf8');
      return {
        id: `${workload.name}/${fileName.replace(/\.rq$/u, '')}`,
        pattern: workload.name,
        mappers,
        userQuery12: query,
        baselineQuery: query,
        materialized: { name: workload.name },
      };
    });
}

export { DATA_DIR, QUERY_DIR };
